AddEventHandler("onResourceStart", function(name)
  if name ~= GetCurrentResourceName() then return end
  show("onResourceStart notifications.broadcast", Open77.notifications.broadcast({ type = "info", title = "probe", message = "start" }))
  show("onResourceStart chat.broadcast", Open77.chat.broadcast("probe onResourceStart"))
  show("onResourceStart chat.addSuggestions(-1)", Open77.chat.addSuggestions(-1, { { command = "/probe", help = "x" } }))
  show("onResourceStart TriggerClientEvent", TriggerClientEvent("probe:x", -1, { a = 1 }))
end)
RegisterCommand("probe", function(source, args, raw)
  show("probe cmd source", source, type(source)); show("probe cmd args.n", args.n, type(args[1]), args[1], args[2]); show("probe cmd raw", raw)
end, false)
