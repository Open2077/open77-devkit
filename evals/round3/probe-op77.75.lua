-- eval_probe: runtime truths for the devkit notes (top level = chunk load)
local function show(label, ...)
  local parts = {}
  for i = 1, select("#", ...) do parts[#parts + 1] = tostring((select(i, ...))) end
  print(("[probe] %s -> %s"):format(label, table.concat(parts, ", ")))
end
